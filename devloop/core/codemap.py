"""The code index (D-038, D-084 Q11): a generated map of the code, so an agent reads one file
instead of grepping the tree. Written by the controller onto the integration branch right before
main moves, so it always matches main; nobody edits it by hand and tickets never touch it.

Python files list their classes and functions with the first line of each docstring (from the
syntax tree); other source files list their first comment line. Tests and generated files are
included only by path.
"""

import ast
import os

from .gitx import Git

SOURCE = (".py", ".sh", ".js", ".jsx", ".ts", ".tsx", ".go", ".rs", ".rb", ".java", ".kt",
          ".swift", ".c", ".h", ".cc", ".cpp", ".cs", ".php")
HEADER = ("# Code map\n\nGenerated by devloop at every landing from the code itself. Do not edit;"
          " read it before searching the tree.\n")


def first_line(text):
    for line in (text or "").strip().splitlines():
        if line.strip():
            return line.strip()[:140]
    return ""


def args(fn):
    names = [a.arg for a in fn.args.args if a.arg not in ("self", "cls")]
    if fn.args.vararg:
        names.append("*" + fn.args.vararg.arg)
    names += [a.arg for a in fn.args.kwonlyargs]
    if fn.args.kwarg:
        names.append("**" + fn.args.kwarg.arg)
    return ", ".join(names)


def python_entries(path):
    try:
        with open(path, errors="replace") as fh:
            tree = ast.parse(fh.read())
    except (OSError, SyntaxError, ValueError):
        return "", []
    out = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            out.append("- class `%s` %s" % (node.name, first_line(ast.get_docstring(node))))
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)) and not sub.name.startswith("_"):
                    out.append("  - `%s(%s)` %s" % (sub.name, args(sub), first_line(ast.get_docstring(sub))))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append("- `%s(%s)` %s" % (node.name, args(node), first_line(ast.get_docstring(node))))
    return first_line(ast.get_docstring(tree)), out


def comment_line(path):
    try:
        with open(path, errors="replace") as fh:
            for _ in range(15):
                line = fh.readline()
                if not line:
                    break
                s = line.strip()
                if s.startswith(("#!", "#!/")):
                    continue
                if s.startswith(("#", "//", "/*", "*", "--")):
                    return s.lstrip("#/*- ").strip()[:140]
    except OSError:
        pass
    return ""


def build(tree, skip=()):
    """The index text for the checkout at `tree`."""
    files = [f for f in Git(tree).out("ls-files").splitlines() if f and f not in skip]
    out = [HEADER]
    for rel in sorted(files):
        if not rel.endswith(SOURCE):
            continue
        path = os.path.join(tree, rel)
        if rel.endswith(".py"):
            doc, entries = python_entries(path)
            out.append("## %s%s" % (rel, " - " + doc if doc else ""))
            out.extend(entries)
        else:
            note = comment_line(path)
            out.append("## %s%s" % (rel, " - " + note if note else ""))
        out.append("")
    return "\n".join(out).rstrip() + "\n"
